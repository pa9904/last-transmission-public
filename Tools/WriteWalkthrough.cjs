function classify(sequence) {
  const choices = sequence.map((n, i) => story.calls[i].choices[n - 1]);
  const flags = new Set(choices.map(c => c.flag));
  const approvals = ['trustedbridge', 'trustedpassword', 'invitedecho'].filter(f => flags.has(f)).length;
  const technician = flags.has('technician');
  const request = flags.has('verified'); // Data means a request; gameplay still requires the hardware test.
  return { choices, rescued: choices.reduce((n, c) => n + c.rescue, 0), approvals, technician, request, eligible: technician && request };
}
function route(title, sequence, description, finalSteps) {
  add('', title, '-'.repeat(64), description, '', '무전 응답 번호: ' + sequence.join(' → '), '');
  sequence.forEach((n, i) => add(`  교신 ${i + 1} / ${story.calls[i].frequency} MHz / 응답 ${n}번`, '  "' + story.calls[i].choices[n - 1].text + '"', ''));
  add('마지막 행동:');
  finalSteps.forEach((s, i) => add(`  ${i + 1}. ${s}`));
  add('', '이 예시의 구조 연결 통계: ' + classify(sequence).rescued + '명');
}

